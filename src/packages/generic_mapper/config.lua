description = [[# generic_mapper Package

This script allows for semi-automatic mapping using the included triggers.
While different games can have dramatically different ways of displaying
information, some effort has been put into giving the script a wide range of
potential patterns to look for, so that it can work with minimal effort in
many cases.

generic_mapper looks at a combination of room titles, descriptions and exits
to locate and follow your character around maps you can make yourself, share
and download for your MUD.

Two commands to get started are;
```
> map basics
> map help
```

See [this forum thread](https://forums.mudlet.org/viewtopic.php?f=13&t=6105) for further assistance.

