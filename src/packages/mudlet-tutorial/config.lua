### Description

Mudlet provides a simple tutorial to help you get familiar with playing MUDs using Mudlet.

You play a young adventurer who has recently graduated from the adventuring school.  You must aid the Sheriff in a series of tasks for the townfolk and become a local hero.

### Usage

After installing, just following along with the onscreen commands.

