This packages allows a user to drag and drop an image on the main screen which will turn it into a label and AdjustableContainer.
The resultant script can be found in GUIDropManager which can then be tailored further as per normal scripting rules.  The images
are copied to %user-profile/GUIDropImages/

### Usage

Just drop an image file into the main window.  It will be converted into a label inside an AdjustableContainer.
